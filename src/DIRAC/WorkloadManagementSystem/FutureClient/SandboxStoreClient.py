"""DiracX implementation of the SandboxStore client.

Sandboxes are transferred directly between the client and the DiracX S3
backend using presigned URLs, without going through the SandboxStore service.
"""
from __future__ import annotations

import hashlib
import os
import random
import re
import time
from collections.abc import Callable, Iterator
from contextlib import contextmanager
from http import HTTPStatus
from typing import TYPE_CHECKING, TypeVar

import requests
from azure.core.exceptions import HttpResponseError
from diracx.client.models import SandboxInfo

from DIRAC import gConfig, gLogger
from DIRAC.ConfigurationSystem.Client.Helpers import Registry
from DIRAC.ConfigurationSystem.Client.PathFinder import getServiceSection
from DIRAC.Core.Security.DiracX import DiracXClient, FutureClient
from DIRAC.Core.Utilities.ReturnValues import SErrorException, convertToReturnValue, returnValueOrRaise

if TYPE_CHECKING:
    from diracx.client.sync import SyncDiracClient

T = TypeVar("T")

# PFNs generated by DiracX look like /S3/<bucket>/<vo>/<group>/<user>/<algorithm>:<checksum>.<format>
RE_S3_PFN = re.compile(
    r"^/S3/[^/]+/(?:[^/]+/){3}(?P<algorithm>[a-z0-9]+):(?P<checksum>[0-9a-f]+)\.(?P<format>[a-z0-9.]+)$"
)
# Name of the SE used by DiracX for sandboxes, only used to build "SB:<SE>|<PFN>" URLs
DIRACX_SANDBOX_SE = "SandboxSE"

MAX_ATTEMPTS = 5
BACKOFF_BASE_SECONDS = 2
BACKOFF_MAX_SECONDS = 60
CHUNK_SIZE = 1024 * 1024
# (connect, read) timeouts in seconds
DOWNLOAD_TIMEOUT = (30, 60)
UPLOAD_TIMEOUT = (30, 300)


class ChecksumMismatchError(Exception):
    pass


def _isRetryable(exc: Exception) -> bool:
    """Whether a transfer to/from the S3 backend is worth retrying"""
    if isinstance(exc, (requests.ConnectionError, requests.Timeout, ChecksumMismatchError)):
        return True
    if isinstance(exc, requests.HTTPError) and exc.response is not None:
        # 403 is returned by S3 if the presigned URL expired, a new one is requested on each attempt
        status = exc.response.status_code
        return status >= 500 or status in (HTTPStatus.FORBIDDEN, HTTPStatus.TOO_MANY_REQUESTS)
    return False


def _withRetries(description: str, func: Callable[[], T]) -> T:
    """Call func, retrying with a jittered exponential backoff if it fails with a retryable error"""
    for attempt in range(1, MAX_ATTEMPTS + 1):
        try:
            return func()
        except Exception as e:
            if attempt == MAX_ATTEMPTS or not _isRetryable(e):
                raise
            # Full jitter avoids many clients retrying in lockstep if the backend has a hiccup
            delay = random.uniform(0, min(BACKOFF_MAX_SECONDS, BACKOFF_BASE_SECONDS * 2**attempt))  # nosec B311
            gLogger.warn(f"Failed {description}, retrying", f"in {delay:.1f}s (attempt {attempt}): {e!r}")
            time.sleep(delay)
    raise NotImplementedError("This should never be reached")


class SandboxStoreClient(FutureClient):
    def __init__(self, delegatedDN: str | None = None, delegatedGroup: str | None = None, **kwargs):
        """
        :param delegatedDN: DN of the user to act on behalf of, requires the DiracX legacy exchange key
        :param delegatedGroup: group of the user to act on behalf of
        """
        self.delegatedDN = delegatedDN
        self.delegatedGroup = delegatedGroup
        self.serviceSection = getServiceSection("WorkloadManagement/SandboxStore")

    @contextmanager
    def _client(self) -> Iterator[SyncDiracClient]:
        if self.delegatedGroup:
            # Only available on servers which have /DiracX/LegacyExchangeApiKey
            from DIRAC.FrameworkSystem.Utilities.diracx import TheImpersonator

            credDict = {
                "username": returnValueOrRaise(Registry.getUsernameForDN(self.delegatedDN)),
                "group": self.delegatedGroup,
                "properties": Registry.getPropertiesForGroup(self.delegatedGroup),
            }
            with TheImpersonator(credDict, source="SandboxStoreClient") as api:
                yield api
        else:
            with DiracXClient() as api:
                yield api

    @convertToReturnValue
    def uploadSandbox(self, tarFilePath: str, assignTo: dict[str, str], sbFormat: str = "tar.bz2") -> str:
        """Upload a sandbox and optionally assign it to jobs as an output sandbox

        :param tarFilePath: path of the sandbox archive
        :param assignTo: dict of {"Job:<jobID>": "Output"}
        :param sbFormat: format of the archive
        :returns: the sandbox URL, i.e. "SB:<SE>|<PFN>"
        """
        jobIDs = []
        for entity, sbType in assignTo.items():
            if not entity.startswith("Job:") or sbType != "Output":
                raise NotImplementedError(f"DiracX can only assign output sandboxes to jobs, got {entity}={sbType}")
            jobIDs.append(int(entity.removeprefix("Job:")))

        size = os.stat(tarFilePath).st_size
        maxBytes = gConfig.getValue(f"{self.serviceSection}/MaxSandboxSizeMiB", 10) * 1048576
        if maxBytes and size > maxBytes:
            raise SErrorException("Sandbox is too big. Please upload it to a grid storage element")

        hasher = hashlib.sha256()
        with open(tarFilePath, "rb") as fh:
            while data := fh.read(CHUNK_SIZE):
                hasher.update(data)
        sandboxInfo = SandboxInfo(checksum_algorithm="sha256", checksum=hasher.hexdigest(), size=size, format=sbFormat)

        def attempt() -> str:
            with self._client() as api:
                res = api.jobs.initiate_sandbox_upload(sandboxInfo)
            if res.url:
                with open(tarFilePath, "rb") as fh:
                    response = requests.post(
                        res.url, data=res.fields, files={"file": ("file", fh)}, timeout=UPLOAD_TIMEOUT
                    )
                response.raise_for_status()
                gLogger.verbose("Uploaded sandbox", res.pfn)
            else:
                gLogger.verbose("Sandbox already exists in storage backend", res.pfn)
            return res.pfn

        sbURL = _withRetries("sandbox upload", attempt)

        with self._client() as api:
            for jobID in jobIDs:
                try:
                    api.jobs.assign_sandbox_to_job(jobID, sbURL.split("|", 1)[-1])
                except HttpResponseError as e:
                    # Identical sandboxes have the same PFN so a rescheduled job can upload the same one again
                    if e.status_code != HTTPStatus.BAD_REQUEST or "already assigned" not in str(e):
                        raise
        return sbURL

    @convertToReturnValue
    def downloadSandbox(self, pfn: str, destination: str) -> None:
        """Download a sandbox from S3 and verify its checksum

        :param pfn: PFN of the sandbox, i.e. "/S3/..."
        :param destination: path the sandbox archive is written to
        """
        if not (match := RE_S3_PFN.match(pfn)):
            raise ValueError(f"Not a DiracX sandbox PFN: {pfn}")

        def attempt() -> None:
            with self._client() as api:
                res = api.jobs.get_sandbox_file(pfn=pfn)
            hasher = hashlib.new(match["algorithm"])
            with requests.get(res.url, stream=True, timeout=DOWNLOAD_TIMEOUT) as response:
                response.raise_for_status()
                with open(destination, "wb") as fh:
                    for chunk in response.iter_content(CHUNK_SIZE):
                        hasher.update(chunk)
                        fh.write(chunk)
            if hasher.hexdigest() != match["checksum"]:
                raise ChecksumMismatchError(f"Checksum mismatch for {pfn}: got {hasher.hexdigest()}")

        _withRetries(f"download of {pfn}", attempt)

    @convertToReturnValue
    def getSandboxesAssignedToJob(self, jobID: int) -> dict[str, list[str]]:
        """Get the sandboxes assigned to a job

        :returns: dict of {"Input"|"Output": ["SB:<SE>|<PFN>", ...]}
        """
        with self._client() as api:
            sandboxes = api.jobs.get_job_sandboxes(int(jobID))
        # Sandboxes which predate the S3 backend are stored on the LocalSE of the SandboxStore
        legacySE = gConfig.getValue(f"{self.serviceSection}/LocalSE", "ProductionSandboxSE")
        sbDict = {}
        for sbType, pfns in sandboxes.items():
            # DiracX returns [None] if there is no sandbox of this type
            for pfn in filter(None, pfns):
                seName = DIRACX_SANDBOX_SE if pfn.startswith("/S3/") else legacySE
                sbDict.setdefault(sbType, []).append(f"SB:{seName}|{pfn}")
        return sbDict
